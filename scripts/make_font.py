#!/usr/bin/env python3
"""Rasterize the UI subset of OFL Noto Sans SC into LVGL 4bpp C data.

Needs Pillow. Generated C is checked in; normal firmware builds need no font tools.
"""
from pathlib import Path
import hashlib
import json
import re
import sys
from PIL import Image, ImageDraw, ImageFont

project = Path(__file__).resolve().parents[1]
font_path = Path(sys.argv[1]) if len(sys.argv) > 1 else project / "assets/fonts/NotoSansSC-subset.ttf"
source = (project / "main/pet_ui.c").read_text()
strings = re.findall(r'"([^"\n]*[\u4e00-\u9fff][^"\n]*)"', source)
chars = sorted(set("".join(strings) + "".join(chr(i) for i in range(32, 127))), key=ord)
font = ImageFont.truetype(str(font_path), 18)
missing_glyph = bytes(font.getmask("\U0010ffff"))
for char in chars:
    if char != " " and bytes(font.getmask(char)) == missing_glyph:
        raise ValueError(f"Source font subset lacks U+{ord(char):04X} {char!r}; obtain an updated subset")
bitmaps = bytearray()
descriptors = ["    {0}, /* reserved glyph */"]
for char in chars:
    x0, y0, x1, y1 = font.getbbox(char, anchor="ls")
    w, h = x1 - x0, y1 - y0
    bitmap_index = len(bitmaps)
    if w and h:
        image = Image.new("L", (w, h))
        ImageDraw.Draw(image).text((-x0, -y0), char, font=font, fill=255, anchor="ls")
        coverage = [(v + 8) // 17 for v in image.tobytes()]
        if len(coverage) % 2: coverage.append(0)
        bitmaps.extend((coverage[i] << 4) | coverage[i + 1] for i in range(0, len(coverage), 2))
    descriptors.append(
        f"    {{.bitmap_index={bitmap_index}, .adv_w={round(font.getlength(char)*16)}, "
        f".box_w={w}, .box_h={h}, .ofs_x={x0}, .ofs_y={-y1}}}, /* U+{ord(char):04X} */")

bitmap_rows = ["    " + ", ".join(f"0x{v:02x}" for v in bitmaps[i:i+16]) + ","
               for i in range(0, len(bitmaps), 16)]
codepoints = ", ".join(str(ord(c)) for c in chars)
offsets = ", ".join(str(ord(c) - ord(chars[0])) for c in chars)
out = """/* Generated by scripts/make_font.py. Glyphs derived from Noto Sans SC.
 * Font bitmap data licensed under SIL OFL 1.1; see assets/fonts/OFL.txt.
 * Font name MOCHI UI 18 (a renamed application subset).
 */
#include "pet_font.h"
static const uint8_t glyph_bitmap[] = {
""" + "\n".join(bitmap_rows) + "\n};\n"
out += "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {\n" + "\n".join(descriptors) + "\n};\n"
out += f"static const uint16_t unicode_list[] = {{{offsets}}};\n"
out += f"const uint32_t pet_font_codepoints[] = {{{codepoints}}};\n"
out += f"const unsigned pet_font_codepoint_count = {len(chars)};\n"
out += f"""static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start={ord(chars[0])}, .range_length={ord(chars[-1])-ord(chars[0])+1}, .glyph_id_start=1,
      .unicode_list=unicode_list, .list_length={len(chars)}, .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}
}};
static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap=glyph_bitmap, .glyph_dsc=glyph_dsc, .cmaps=cmaps,
    .cmap_num=1, .bpp=4, .bitmap_format=LV_FONT_FMT_TXT_PLAIN
}};
const lv_font_t pet_font_18 = {{
    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,
    .line_height=24, .base_line=6, .dsc=&font_dsc,
    .underline_position=-2, .underline_thickness=1
}};
"""
(project / "main/pet_font.c").write_text(out)
(project / "assets/fonts/font-source.json").write_text(json.dumps({
    "family": "MOCHI UI 18", "source_font": "Noto Sans SC Regular, Google Fonts text subset",
    "url": "https://fonts.google.com/noto/specimen/Noto+Sans+SC",
    "source_sha256": hashlib.sha256(font_path.read_bytes()).hexdigest(),
    "license": "SIL OFL 1.1", "size_px": 18, "bpp": 4,
    "codepoints": [ord(c) for c in chars], "strings": strings,
}, ensure_ascii=False, indent=2) + "\n")
print(f"Generated MOCHI UI 18: {len(chars)} glyphs, {len(bitmaps)} bitmap bytes")
